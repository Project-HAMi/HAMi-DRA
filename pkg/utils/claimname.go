package utils

import "strings"

// claimNamePrefixMax is the longest "<namespace>-<owner>-" prefix that survives
// the DNS-1123 truncation applied to generated claim names (63 minus a "-"
// and an 8 character hash).
const claimNamePrefixMax = 54

// OwnsClaimName reports whether name could have been generated by the webhook
// for the given namespace and owner (Pod or Job). Generated names start with
// "<namespace>-<owner>-", so user-managed claims and templates that happen to
// be listed in a Pod or Job are left alone.
func OwnsClaimName(name, namespace, owner string) bool {
	prefix := namespace + "-" + owner + "-"
	if len(prefix) > claimNamePrefixMax {
		prefix = strings.TrimRight(prefix[:claimNamePrefixMax], "-")
	}
	return strings.HasPrefix(name, prefix)
}
